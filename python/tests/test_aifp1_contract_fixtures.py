"""The backend's own 402, quote and receipt (contract-fixtures/aifp1) through this SDK's checks.

Generated by aifinpay-web test/aifp1-contract-fixtures.test.js; the Node SDK replays the
same files through its full purchase path.
"""

import hashlib
import json
import pathlib

import pytest

import aifinpay.aifp1 as a
from aifinpay.payment_chains import PAYMENT_CHAINS

DIR = pathlib.Path(__file__).resolve().parents[2] / "contract-fixtures" / "aifp1"
MANIFEST = json.loads((DIR / "MANIFEST.json").read_text())


class Resp:
    def __init__(self, body):
        self.status_code = 200
        self.ok = True
        self._body = body
        self.text = json.dumps(body)

    def json(self):
        return self._body


class Session:
    def __init__(self, fixture):
        self.fixture = fixture

    def get(self, url, **_kwargs):
        assert url == self.fixture["api_base"] + "/.well-known/jwks.json"
        return Resp({"keys": [self.fixture["issuer_jwk"]]})


def test_vendored_fixtures_are_the_ones_their_manifest_pins():
    for name, digest in MANIFEST["files"].items():
        assert hashlib.sha256((DIR / name).read_bytes()).hexdigest() == digest, name


@pytest.mark.parametrize("name", sorted(MANIFEST["files"]))
def test_backend_quote_and_receipt_pass_this_sdk(name, monkeypatch):
    f = json.loads((DIR / name).read_text())
    quote = f["quote"]
    call = quote["settlement_call"]
    chain, asset = call["chain"], call["asset"]
    monkeypatch.setattr(a.time, "time", lambda: a._iso_to_unix(f["generated_at"]) + 1)

    assert a.default_units_for(f["challenge_402"]) == f["quote_request"]["units"]
    expiry_s = a._iso_to_unix(quote["expires_at"])
    if asset == PAYMENT_CHAINS[chain]["native"]:
        rate = float(quote["native_settlement"]["rate_usd"])
        a.validate_native_quote(quote, f["payer"], expiry_s, rate, chain)
    else:
        a.validate_stable_quote(quote, asset, f["payer"], expiry_s, chain)

    paid = dict(f["pay_response"], receipt=".".join(f["receipt_jwt_parts"]))
    a.verify_paid_receipt(paid, quote, asset, paid["tx_ref"], f["payer"], f["api_base"], Session(f), chain)
